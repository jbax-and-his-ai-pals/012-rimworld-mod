using System.Linq;
using RimWorld;
using RimWorld.Planet;
using Verse;

namespace Site44
{
    [StaticConstructorOnStartup]
    public static class Site44Mod
    {
        // Dev escape hatch: -quicktest always forces Crashlanded, so this lets it build the facility instead.
        private const string TestArg = "site44test";

        static Site44Mod()
        {
            Log.Message("[Site-44] loaded.");
            ApplyQuestFrequency();
        }

        // The ruin quest is picked by weight among opportunity quests; the setting scales that weight.
        public static void ApplyQuestFrequency()
        {
            foreach (SiteTypeDef type in SiteTypes.All)
            {
                if (type.questScript != null)
                {
                    type.questScript.rootSelectionWeight = type.questWeight * Site44Settings.Current.questFrequency;
                }
            }
        }


        public static bool ShouldGenerateFacility(Map map)
        {
            // A ruined-complex world site generated by the ruin quest.
            if (SiteTypes.ForSite(map?.Parent as Site) != null)
            {
                return true;
            }

            // Otherwise only the initial colony map; later maps (and loaded saves) never see game init data.
            if (Find.GameInitData == null)
            {
                return false;
            }

            return GenCommandLine.CommandLineArgPassed(TestArg)
                || Find.Scenario.AllParts.Any(p => p is ScenPart_Site44Facility);
        }
    }
}

